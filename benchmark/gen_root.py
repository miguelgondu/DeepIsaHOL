#!/usr/bin/env python3
"""Generate DeepIsaHOL/benchmark/ROOT from two env vars.

Run at Docker build time (see ../Dockerfile), before the `isabelle build`
step that turns this into the prebuilt `Benchmark` heap. Writes the ROOT
file to stdout so the caller can redirect it.

  DEEPISAHOL_PARENT_SESSION - the session `Benchmark` extends (default
                               "HOL"). Anything already shipped or buildable
                               by this Isabelle distribution works, e.g.
                               "HOL-Analysis" or "HOL-Probability".
  DEEPISAHOL_EXTRA_SESSIONS - comma-separated sibling sessions built and
                               loaded alongside the parent (default: none).
                               Each name must be a key in UMBRELLA_THEORIES
                               below.

Both default to the cheapest possible heap: `Benchmark` = bare `HOL`, which
ships prebuilt with the Isabelle distribution, so the resulting
`isabelle build` is a no-op (seconds, not the ~1-2h a full library set
costs). See DeepIsaHOL/README.md for the env vars and worked examples.
"""

import os
import sys

# Session name -> theories to put in Benchmark's `theories` clause, so a
# generated theory can `imports` the session directly with no on-the-fly
# build. Usually just that session's own umbrella theory (which doesn't
# always match the session name, e.g. HOL-Decision_Procs's is
# `Approximation`) -- except `HOL-Library`, which has no single umbrella and
# lists the specific method-bearing theories worth always having loaded
# (`sos`, quadratic-discriminant, executable numerals). Extend this table
# when adding support for a new session to DEEPISAHOL_EXTRA_SESSIONS.
UMBRELLA_THEORIES: dict[str, list[str]] = {
    "HOL-Analysis": ["HOL-Analysis.Analysis"],
    "HOL-Probability": ["HOL-Probability.Probability"],
    "HOL-Number_Theory": ["HOL-Number_Theory.Number_Theory"],
    "HOL-Algebra": ["HOL-Algebra.Algebra"],
    "HOL-Combinatorics": ["HOL-Combinatorics.Combinatorics"],
    "HOL-Cardinals": ["HOL-Cardinals.Cardinals"],
    "HOL-Computational_Algebra": ["HOL-Computational_Algebra.Computational_Algebra"],
    "HOL-Decision_Procs": ["HOL-Decision_Procs.Approximation"],
    "HOL-Real_Asymp": ["HOL-Real_Asymp.Real_Asymp"],
    "HOL-Eisbach": ["HOL-Eisbach.Eisbach"],
    "HOL-Library": [
        "HOL-Library.Sum_of_Squares",
        "HOL-Library.Quadratic_Discriminant",
        "HOL-Library.Code_Target_Numeral",
    ],
}


def main() -> None:
    parent = os.environ.get("DEEPISAHOL_PARENT_SESSION", "HOL").strip() or "HOL"
    extras_raw = os.environ.get("DEEPISAHOL_EXTRA_SESSIONS", "").strip()
    extras = [s.strip() for s in extras_raw.split(",") if s.strip()]

    unknown = [s for s in extras if s not in UMBRELLA_THEORIES]
    if unknown:
        sys.exit(
            "gen_root.py: unsupported session(s) in DEEPISAHOL_EXTRA_SESSIONS: "
            f"{', '.join(unknown)}. Known sessions: "
            f"{', '.join(sorted(UMBRELLA_THEORIES))}. If this session is "
            "genuinely new, add it (and its umbrella theory) to "
            "UMBRELLA_THEORIES in this script."
        )

    lines = [
        "chapter Benchmark",
        "",
        "(*",
        "  Auto-generated by gen_root.py from DEEPISAHOL_PARENT_SESSION /",
        "  DEEPISAHOL_EXTRA_SESSIONS at Docker build time -- do not edit by",
        "  hand, edit those env vars instead (see DeepIsaHOL/README.md) and",
        "  rerun the build. The running server reports this same composition",
        "  live at GET /sessions.",
        "*)",
        "",
        f'session Benchmark = "{parent}" +',
        "  description",
        f'    "Parent: {parent}. Extra sessions: {", ".join(extras) or "(none)"}."',
    ]
    if extras:
        lines.append("  sessions")
        lines.extend(f'    "{s}"' for s in extras)
        lines.append("  theories")
        for s in extras:
            lines.extend(f'    "{t}"' for t in UMBRELLA_THEORIES[s])

    sys.stdout.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
